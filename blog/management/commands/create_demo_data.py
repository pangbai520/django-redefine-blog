class Command(BaseCommand):
    help = "Create a small, repeatable demo set without touching user-authored content."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Delete only records created by this command.",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        demo_articles = ArticleModel.objects.filter(slug__startswith=DEMO_PREFIX)
        if options["clear"]:
            deleted = demo_articles.count()
            demo_articles.delete()
            self.stdout.write(self.style.SUCCESS(f"Removed {deleted} demo article(s)."))
            return

        category, _ = Category.objects.get_or_create(
            slug="getting-started", defaults={"name": "Getting Started"}
        )
        tag, _ = Tag.objects.get_or_create(slug="demo", defaults={"name": "Demo"})
        created = 0
        for offset, values in enumerate(DEMO_ARTICLES):
            article, was_created = ArticleModel.objects.update_or_create(
                slug=values["slug"],
                defaults={
                    **values,
                    "writer": "The Redefine Team",
                    "is_published": True,
                    "created_at": timezone.now() - timedelta(days=offset),
                },
            )
            article.category.set([category])
            article.tags.set([tag])
            created += int(was_created)

        self.stdout.write(
            self.style.SUCCESS(
                f"Demo data ready: {created} created, {len(DEMO_ARTICLES) - created} updated."
            )
        )
