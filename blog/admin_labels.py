def apply_admin_metadata(model_namespace):
    """Apply lazy, editorial labels without changing the database schema."""
    for model_name, (singular, plural) in MODEL_LABELS.items():
        model = model_namespace.get(model_name)
        if model is None:
            continue
        model._meta.verbose_name = singular
        model._meta.verbose_name_plural = plural
